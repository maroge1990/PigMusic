"""Writes the iPhone's copy of the server's text normalising for favourites
(Codex round 2 on batch G) from this Python's own Unicode data:

- swift/PigKit/Sources/PigDomain/FavouriteFolding.swift: `str.casefold()`
  for every character it changes, and the ranges of characters Python's
  `\\w` takes for word characters;
- tests/fixtures/favourite_normalise.json: strings and what the server's
  `library.normalise` makes of them, which PigKit's FavouriteMatchTests
  checks the Swift copy against.

Run it again after a Python upgrade; `--check` (run by
tests/test_favourite_matching.py) fails while the files are out of date.

    .venv/bin/python scripts/generate_favourite_folding.py [--check]
"""

import argparse
import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SWIFT = ROOT / "swift/PigKit/Sources/PigDomain/FavouriteFolding.swift"
FIXTURE = ROOT / "tests/fixtures/favourite_normalise.json"
WORD = re.compile(r"\w")


def characters():
    for code in range(sys.maxunicode + 1):
        if 0xD800 <= code <= 0xDFFF:
            continue
        yield code, chr(code)


def folds():
    return {
        code: [ord(c) for c in char.casefold()]
        for code, char in characters()
        if char.casefold() != char
    }


def word_ranges():
    ranges = []
    for code, char in characters():
        if WORD.match(char):
            if ranges and ranges[-1][1] == code - 1:
                ranges[-1][1] = code
            else:
                ranges.append([code, code])
    return ranges


def swift_source():
    fold_lines = "\n".join(
        f"    0x{code:X}: [{', '.join(f'0x{v:X}' for v in values)}],"
        for code, values in sorted(folds().items())
    )
    range_lines = "\n".join(
        f"    (0x{low:X}, 0x{high:X})," for low, high in word_ranges()
    )
    return f"""// Generated by scripts/generate_favourite_folding.py from Python's
// Unicode {unicodedata.unidata_version} data; do not edit. Run it again after a
// Python upgrade (tests/test_favourite_matching.py fails until then).

/// Python's `str.casefold()` and `\\w`, as the server's `library.normalise`
/// uses them (Codex round 2 on batch G).
enum FavouriteFolding {{
  /// Every character `str.casefold()` changes, and what it becomes.
  static let folds: [UInt32: [UInt32]] = [
{fold_lines}
  ]
  /// The characters Python's `\\w` matches, as sorted inclusive ranges.
  static let wordRanges: [(UInt32, UInt32)] = [
{range_lines}
  ]
}}
"""


def normalise(text):
    """The server's library.normalise, inlined so the generator needs no
    server imports; tests/test_favourite_matching.py checks they agree."""
    text = unicodedata.normalize("NFKC", text or "").casefold()
    return " ".join(re.findall(r"\w+", text))


def cases():
    texts = []
    # Every character case folding changes, alone and inside a word.
    for code in sorted(folds()):
        char = chr(code)
        texts += [char, f"x{char}y", f"{char.upper()} {char}"]
    # Every mark, punctuation, symbol and separator below U+3000, and other
    # characters NFKC changes there: where words break and what joins them.
    for code, char in characters():
        if code >= 0x3000:
            break
        category = unicodedata.category(char)
        if category[0] in "MPSZ" or unicodedata.normalize("NFKC", char) != char:
            texts.append(f"a{char}b")
    # Words from the matching fixture and a few whole names.
    texts += [
        "Maße",
        "MASSE",
        "ẞ",
        "ı",
        "İstanbul",
        "Track_A",
        "Ⅻ Roman",
        "ﬁre",
        "ΟΔΟΣ οδος",
        "夜に駆ける",
        "Beyoncé feat. JAY-Z",
        "Sigur Rós",
        "Motörhead",
        "AC/DC",
        "",
    ]
    seen = set()
    unique = [t for t in texts if not (t in seen or seen.add(t))]
    return [{"text": t, "normalised": normalise(t)} for t in unique]


def fixture_source():
    return (
        json.dumps(
            {
                "about": "Generated by scripts/generate_favourite_folding.py from Python's Unicode "
                + unicodedata.unidata_version
                + " data: each text and what the server's library.normalise makes of it.",
                "cases": cases(),
            },
            ensure_ascii=True,
            indent=0,
        )
        + "\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    stale = []
    for path, text in ((SWIFT, swift_source()), (FIXTURE, fixture_source())):
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        sys.exit(
            "Out of date, run scripts/generate_favourite_folding.py: "
            + ", ".join(stale)
        )


if __name__ == "__main__":
    main()
